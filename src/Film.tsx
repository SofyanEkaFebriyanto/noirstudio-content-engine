/**
 * Film — the composition. Turns a resolved episode into the actual timeline.
 *
 * Scene bodies render inside TransitionSeries. Audio, captions and the HUD live
 * outside it so they are never duplicated or faded by a transition.
 */
import React from 'react';
import { AbsoluteFill, Sequence } from 'remotion';
import { TransitionSeries, linearTiming } from '@remotion/transitions';
import type { EpisodeParsed } from './engine/spec';
import { FORMATS } from './engine/spec';
import type { VoAlignment } from './engine/captions';
import { buildCaptions } from './engine/captions';
import { resolveTimeline } from './engine/timeline';
import { getTheme, type ShotContext } from './engine/theme';
import { getShot } from './shots/registry';
import { mediaUrl, audioUrl } from './engine/assets';
import { getPresentation } from './engine/presentations';
import { Captions } from './components/Captions';
import { MusicBed, Cue } from './audio/AudioLayer';
import { VoiceLayer } from './audio/VoiceLayer';
import type { MediaManifest } from './engine/assets';

/**
 * Fill a shot's props with its schema defaults, then layer the episode's
 * values on top. Safe when required fields are only supplied by the episode.
 */
/**
 * Resolve a scene's props against its shot schema.
 *
 * Parsing the *actual* props is what applies `.default()` values. Parsing `{}`
 * — the earlier approach — silently yields nothing whenever the schema has a
 * required field, so every default was dropped: a counter rendered with three
 * decimals because `decimals: 0` never arrived. Since `check` rejects invalid
 * props before a render, a parse failure here means the generated episode is
 * stale; fall back to the raw props rather than crashing the whole film.
 */
function withDefaults(
  schema: { safeParse: (value: unknown) => { success: boolean; data?: unknown } },
  props: Record<string, unknown>,
): Record<string, unknown> {
  const parsed = schema.safeParse(props);
  if (parsed.success && parsed.data && typeof parsed.data === 'object') {
    return parsed.data as Record<string, unknown>;
  }
  return props;
}

export type FilmProps = {
  episode: EpisodeParsed;
  /** Generated by `npm run sync`. */
  media: MediaManifest;
  /** Generated by `npm run vo`; empty when no VO exists yet. */
  alignments: VoAlignment[];
  /** VO segment ids with audio files present. */
  voAvailable: string[];
  /** Inventory of vendored audio so missing files are skipped, not fatal. */
  audioPack: { cues: string[]; music: string[] };
  /** Toggle for the SFX-only cut. */
  music: boolean;
  vo: boolean;
  captions: boolean;
};

export const Film: React.FC<FilmProps> = ({
  episode,
  media,
  alignments,
  voAvailable,
  audioPack,
  music,
  vo,
  captions,
}) => {
  const format = FORMATS[episode.format];
  const theme = getTheme(episode.theme, episode.themeOverrides);
  const timeline = resolveTimeline(episode, { width: format.width, height: format.height });
  const captionLines = buildCaptions(episode, timeline, alignments);

  const ctxFor = (sceneId: string, durationInFrames: number): ShotContext => ({
    theme,
    format: episode.format,
    width: format.width,
    height: format.height,
    fps: episode.fps,
    durationInFrames,
    sceneId,
    episodeId: episode.id,
    media: (id) => mediaUrl(media, id),
    audio: audioUrl,
  });

  return (
    <AbsoluteFill style={{ backgroundColor: theme.colors.bg }}>
      <TransitionSeries>
        {timeline.scenes.map((scene, index) => {
          const shot = getShot(scene.shot);
          if (!shot) return null;
          const Component = shot.component as React.FC<{ props: Record<string, unknown>; ctx: ShotContext }>;
          const ctx = ctxFor(scene.id, scene.durationInFrames);
          return (
            <React.Fragment key={scene.id}>
              {index > 0 && scene.transitionIn ? (
                <TransitionSeries.Transition
                  presentation={getPresentation(scene.transitionIn.type, {
                    direction: scene.transitionIn.direction,
                    wipe: scene.transitionIn.wipe,
                    width: format.width,
                    height: format.height,
                  })}
                  timing={linearTiming({ durationInFrames: scene.transitionIn.durationInFrames })}
                />
              ) : null}
              <TransitionSeries.Sequence durationInFrames={scene.durationInFrames} name={scene.id}>
                <Component props={withDefaults(shot.schema, scene.props)} ctx={ctx} />
              </TransitionSeries.Sequence>
            </React.Fragment>
          );
        })}
      </TransitionSeries>

      <VoiceLayer
        episodeId={episode.id}
        alignments={alignments}
        fps={episode.fps}
        enabled={vo}
        available={voAvailable}
      />

      {episode.audio.music.map((track, index) => (
        <MusicBed
          key={index}
          track={track}
          totalFrames={timeline.durationInFrames}
          fps={episode.fps}
          enabled={music}
          pack={audioPack}
        />
      ))}

      {episode.audio.cues.map((cue, index) => (
        <Cue key={index} cue={cue} fps={episode.fps} pack={audioPack} />
      ))}

      {captions ? (
        <Sequence from={0} durationInFrames={timeline.durationInFrames} name="Captions">
          <Captions
            ctx={ctxFor('captions', timeline.durationInFrames)}
            lines={captionLines}
            style={episode.captions.style === 'plain' ? 'plain' : 'kinetic'}
          />
        </Sequence>
      ) : null}
    </AbsoluteFill>
  );
};
